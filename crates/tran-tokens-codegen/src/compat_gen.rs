//! The API's versioned base path, the compatibility headers and the wire-enum fallbacks from
//! `rust_core::compat` (spec 028, REQ-VER-001, REQ-VER-008), for every client:
//! `packages/api/src/generated/compat.ts`, iOS `Generated/ApiContract.swift` and Android
//! `generated/ApiContract.kt`. No client spells the version or a fallback by hand.

use crate::names::{member_name, pascal_case};
use rust_core::compat::{
    WireEnum, API_BASE_PATH, CLIENT_HEADER, HEALTH_PATH, RECOMMENDED_VERSION_HEADER, UPDATE_HEADER,
    UPDATE_RECOMMENDED, WIRE_ENUMS,
};

/// `(doc, camelCase name, value)` of every string constant, in output order. TypeScript spells
/// the name in capitals, and the base path as `API_BASE_PATH`.
const CONSTANTS: [(&str, &str, &str); 6] = [
    (
        "Every product route lives under this path (REQ-VER-001).",
        "basePath",
        API_BASE_PATH,
    ),
    (
        "The health routes stay unversioned.",
        "healthPath",
        HEALTH_PATH,
    ),
    (
        "Sent with every request: `<platform>/<version>` (REQ-VER-004).",
        "clientHeader",
        CLIENT_HEADER,
    ),
    (
        "Carries `updateRecommended` when the API recommends a newer version (REQ-VER-006).",
        "updateHeader",
        UPDATE_HEADER,
    ),
    (
        "The value of `updateHeader`.",
        "updateRecommended",
        UPDATE_RECOMMENDED,
    ),
    (
        "The recommended version, beside `updateHeader` (REQ-VER-010).",
        "recommendedVersionHeader",
        RECOMMENDED_VERSION_HEADER,
    ),
];

/// `basePath` → `BASE_PATH`.
fn screaming(camel: &str) -> String {
    let mut out = String::new();
    for c in camel.chars() {
        if c.is_ascii_uppercase() {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    out
}

fn quoted_list(values: &[&str], quote: char) -> String {
    values
        .iter()
        .map(|v| format!("{quote}{v}{quote}"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The TypeScript name of a constant: `basePath` would read as any base path in `@tran/api`.
fn ts_name(camel: &str) -> String {
    match camel {
        "basePath" => "API_BASE_PATH".into(),
        other => screaming(other),
    }
}

/// `user_role` → `userRole`.
fn camel(name: &str) -> String {
    member_name(&name.replace('_', "."))
}

const HEADER: &str =
    "@generated by tran-tokens-codegen from crates/rust-core/src/compat.rs — do not edit by hand.";

pub fn render_compat_ts() -> String {
    let mut out = format!(
        "/**\n * {HEADER}\n * Run `pnpm tokens:sync` after changing it (spec 028).\n */\n\n"
    );
    for (doc, name, value) in CONSTANTS {
        out.push_str(&format!(
            "/** {doc} */\nexport const {} = '{value}';\n\n",
            ts_name(name)
        ));
    }
    out.push_str(
        "/** An enum a client decodes, and the value an unknown one reads as (REQ-VER-008). */\nexport interface WireEnum<T extends string = string> {\n  readonly name: string;\n  readonly field: string;\n  readonly values: readonly T[];\n  readonly fallback: T;\n}\n\n",
    );
    for wire in WIRE_ENUMS {
        out.push_str(&format!(
            "export const {constant} = {{\n  name: '{name}',\n  field: '{field}',\n  values: [{values}],\n  fallback: '{fallback}',\n}} as const satisfies WireEnum;\n\n",
            constant = screaming(&camel(wire.name)),
            name = wire.name,
            field = wire.field,
            values = quoted_list(wire.values, '\''),
            fallback = wire.fallback,
        ));
    }
    let all: Vec<String> = WIRE_ENUMS
        .iter()
        .map(|w| screaming(&camel(w.name)))
        .collect();
    out.push_str(&format!(
        "/** Every wire enum, in catalogue order. */\nexport const WIRE_ENUMS: readonly WireEnum[] = [{}];\n",
        all.join(", ")
    ));
    out
}

fn swift_wire_enum(wire: &WireEnum) -> String {
    format!(
        "        enum {name} {{\n            static let field = \"{field}\"\n            static let values: [String] = [{values}]\n            static let fallback = \"{fallback}\"\n        }}\n",
        name = pascal_case(&wire.name.replace('_', "-")),
        field = wire.field,
        values = quoted_list(wire.values, '"'),
        fallback = wire.fallback,
    )
}

pub fn render_compat_swift() -> String {
    let mut out = format!(
        "// {HEADER}\n// Run `pnpm tokens:sync` after changing it (spec 028).\n\n/// The API's versioned base path, the compatibility headers and the wire-enum fallbacks\n/// (REQ-VER-001, REQ-VER-004, REQ-VER-008). Requests use these, never a literal.\nenum ApiContract {{\n"
    );
    for (doc, name, value) in CONSTANTS {
        out.push_str(&format!(
            "    /// {doc}\n    static let {name} = \"{value}\"\n"
        ));
    }
    out.push_str("\n    /// What an unknown value of each wire enum decodes to (REQ-VER-008).\n    enum WireEnums {\n");
    for wire in WIRE_ENUMS {
        out.push_str(&swift_wire_enum(&wire));
    }
    out.push_str("    }\n}\n");
    out
}

pub fn render_compat_kotlin(kotlin_package: &str) -> String {
    let mut out = format!(
        "// {HEADER}\n// Run `pnpm tokens:sync` after changing it (spec 028).\n\npackage {kotlin_package}\n\n/**\n * The API's versioned base path, the compatibility headers and the wire-enum fallbacks\n * (REQ-VER-001, REQ-VER-004, REQ-VER-008). Requests use these, never a literal.\n */\nobject ApiContract {{\n"
    );
    for (doc, name, value) in CONSTANTS {
        out.push_str(&format!(
            "    /** {doc} */\n    const val {name} = \"{value}\"\n"
        ));
    }
    out.push_str(
        "\n    /** What an unknown value of each wire enum decodes to (REQ-VER-008). */\n    object WireEnums {\n",
    );
    for wire in WIRE_ENUMS {
        out.push_str(&format!(
            "        object {name} {{\n            const val field = \"{field}\"\n            val values: List<String> = listOf({values})\n            const val fallback = \"{fallback}\"\n        }}\n",
            name = pascal_case(&wire.name.replace('_', "-")),
            field = wire.field,
            values = quoted_list(wire.values, '"'),
            fallback = wire.fallback,
        ));
    }
    out.push_str("    }\n}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_fold_per_platform() {
        assert_eq!(
            screaming("recommendedVersionHeader"),
            "RECOMMENDED_VERSION_HEADER"
        );
        assert_eq!(camel("country_source"), "countrySource");
        assert_eq!(ts_name("basePath"), "API_BASE_PATH");
        assert_eq!(ts_name("healthPath"), "HEALTH_PATH");
    }

    // Verifies: REQ-VER-001 REQ-VER-008
    #[test]
    fn typescript_carries_the_base_path_and_every_fallback() {
        let ts = render_compat_ts();
        assert!(ts.contains("export const API_BASE_PATH = '/api/v1';"));
        assert!(ts.contains("export const CLIENT_HEADER = 'X-Tran-Client';"));
        assert!(ts.contains("  fallback: 'citizen_voter',\n"));
        assert!(ts.contains("WIRE_ENUMS: readonly WireEnum[] = [USER_ROLE, COUNTRY_SOURCE];"));
    }

    // Verifies: REQ-VER-001 REQ-VER-008
    #[test]
    fn swift_and_kotlin_carry_the_base_path_and_every_fallback() {
        let swift = render_compat_swift();
        assert!(swift.contains("    static let basePath = \"/api/v1\"\n"));
        assert!(swift.contains("        enum UserRole {\n"));
        assert!(swift.contains("static let fallback = \"default\""));
        let kotlin = render_compat_kotlin("com.example");
        assert!(kotlin.contains("package com.example\n"));
        assert!(kotlin.contains("    const val basePath = \"/api/v1\"\n"));
        assert!(kotlin.contains("        object CountrySource {\n"));
        assert!(kotlin.contains("listOf(\"citizen_voter\", \"election_auditor\")"));
    }
}
