//! `packages/core-ts/src/generated/feedback.ts` — the error/feedback catalogue from `rust-core`
//! (ADR-0028, REQ-ERR-001). `messageKey` is typed as `TranStringKey`, so a catalogue entry whose
//! locale string is missing fails `tsc`.

use rust_core::feedback::{
    code_for_http_status, ErrorCode, Presentation, ToastDuration, UserAction, LOG_EVENT,
    REQUEST_ID_MAX_LEN, RETRY_POLICY,
};

fn presentation_ts(presentation: Presentation) -> String {
    match presentation {
        Presentation::Silent => "{ kind: 'silent' }".to_string(),
        Presentation::Inline => "{ kind: 'inline' }".to_string(),
        Presentation::Banner => "{ kind: 'banner' }".to_string(),
        Presentation::Toast { tone, duration } => format!(
            "{{ kind: 'toast', tone: '{}', duration: '{}' }}",
            tone.as_str(),
            duration.as_str()
        ),
        Presentation::Dialog { destructive } => {
            format!("{{ kind: 'dialog', destructive: {destructive} }}")
        }
    }
}

/// `code_for_http_status` sampled over 400–599 and compressed into ranges, so TypeScript reads the
/// Rust decision instead of re-implementing the `match`.
fn status_ranges() -> Vec<(u16, u16, ErrorCode)> {
    let mut ranges: Vec<(u16, u16, ErrorCode)> = Vec::new();
    for status in 400..=599 {
        let code = code_for_http_status(status);
        match ranges.last_mut() {
            Some((_, to, last)) if *last == code && *to + 1 == status => *to = status,
            _ => ranges.push((status, status, code)),
        }
    }
    ranges
}

pub fn render_feedback_ts() -> String {
    let union = |items: Vec<&str>| {
        items
            .iter()
            .map(|item| format!("\n  | '{item}'"))
            .collect::<String>()
    };
    let codes = union(ErrorCode::ALL.iter().map(|c| c.as_str()).collect());
    let actions = union(UserAction::ALL.iter().map(|a| a.as_str()).collect());

    let errors: String = ErrorCode::ALL
        .iter()
        .map(|code| {
            let spec = code.spec();
            let status = spec
                .http_status
                .map_or("null".to_string(), |s| s.to_string());
            format!(
                "  {{\n    code: '{}',\n    httpStatus: {status},\n    retryable: {},\n    logLevel: '{}',\n    presentation: {},\n    messageKey: '{}',\n  }},\n",
                code.as_str(),
                spec.retryable,
                spec.log_level.as_str(),
                presentation_ts(spec.presentation),
                spec.message_key
            )
        })
        .collect();
    let action_rows: String = UserAction::ALL
        .iter()
        .map(|action| {
            let spec = action.spec();
            format!(
                "  {{\n    action: '{}',\n    presentation: {},\n    messageKey: '{}',\n  }},\n",
                action.as_str(),
                presentation_ts(spec.presentation),
                spec.message_key
            )
        })
        .collect();
    let durations: String = ToastDuration::ALL
        .iter()
        .map(|d| format!("  {}: {},\n", d.as_str(), d.millis()))
        .collect();
    let ranges: String = status_ranges()
        .iter()
        .map(|(from, to, code)| {
            format!(
                "  {{ from: {from}, to: {to}, code: '{}' }},\n",
                code.as_str()
            )
        })
        .collect();

    format!(
        "/**\n * @generated by tran-tokens-codegen from crates/rust-core/src/feedback.rs — do not edit by hand.\n * Run `pnpm tokens:sync` after changing the policy in Rust (ADR-0028).\n */\n\n\
import type {{ TranStringKey }} from './keys.js';\n\n\
export type ErrorCode ={codes};\n\n\
export type UserAction ={actions};\n\n\
export type LogLevel = 'debug' | 'info' | 'warn' | 'error';\n\n\
export type ToastTone = 'success' | 'info' | 'warning' | 'error';\n\n\
export type ToastDuration = 'short' | 'medium' | 'long';\n\n\
/** The one way an outcome reaches the user (REQ-ERR-006). */\n\
export type Presentation =\n  | {{ kind: 'silent' }}\n  | {{ kind: 'inline' }}\n  | {{ kind: 'banner' }}\n  | {{ kind: 'toast'; tone: ToastTone; duration: ToastDuration }}\n  | {{ kind: 'dialog'; destructive: boolean }};\n\n\
export interface ErrorSpec {{\n  readonly code: ErrorCode;\n  /** `null` for failures only a client can observe. */\n  readonly httpStatus: number | null;\n  readonly retryable: boolean;\n  readonly logLevel: LogLevel;\n  readonly presentation: Presentation;\n  readonly messageKey: TranStringKey;\n}}\n\n\
export interface ActionSpec {{\n  readonly action: UserAction;\n  readonly presentation: Presentation;\n  readonly messageKey: TranStringKey;\n}}\n\n\
export const ERROR_CATALOGUE: readonly ErrorSpec[] = [\n{errors}];\n\n\
export const ACTION_CATALOGUE: readonly ActionSpec[] = [\n{action_rows}];\n\n\
export const TOAST_DURATIONS_MS: Readonly<Record<ToastDuration, number>> = {{\n{durations}}};\n\n\
export const RETRY_POLICY = {{\n  maxAttempts: {},\n  baseDelayMs: {},\n  maxDelayMs: {},\n  requestTimeoutMs: {},\n}} as const;\n\n\
/** Rust's `code_for_http_status` over 400–599; any other status is `server.internal`. */\n\
export const STATUS_FALLBACK: readonly {{ from: number; to: number; code: ErrorCode }}[] = [\n{ranges}];\n\n\
/** Rust's `is_valid_request_id`: 1–{} characters of `[A-Za-z0-9._-]` (REQ-ROB-010). */\n\
export const REQUEST_ID_PATTERN = /^[A-Za-z0-9._-]{{1,{}}}$/;\n\n\
/** The one log event every platform emits for a failure (REQ-ROB-007). */\n\
export const LOG_EVENT = {{\n  message: '{}',\n  fields: [{}],\n}} as const;\n",
        RETRY_POLICY.max_attempts,
        RETRY_POLICY.base_delay_ms,
        RETRY_POLICY.max_delay_ms,
        RETRY_POLICY.request_timeout_ms,
        REQUEST_ID_MAX_LEN,
        REQUEST_ID_MAX_LEN,
        LOG_EVENT.message,
        LOG_EVENT
            .fields
            .iter()
            .map(|f| format!("'{f}'"))
            .collect::<Vec<_>>()
            .join(", "),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn feedback_ts_carries_every_code_action_and_policy() {
        let ts = render_feedback_ts();
        assert!(ts.contains("@generated by tran-tokens-codegen"));
        for code in ErrorCode::ALL {
            assert!(
                ts.contains(&format!("code: '{}'", code.as_str())),
                "{code:?}"
            );
        }
        assert!(ts.contains(
            "action: 'sign_out',\n    presentation: { kind: 'dialog', destructive: true },"
        ));
        assert!(ts.contains("  short: 3000,"));
        assert!(ts.contains("maxAttempts: 3,"));
    }

    #[test]
    fn status_ranges_cover_400_to_599_without_gaps() {
        let ranges = status_ranges();
        assert_eq!(ranges.first().map(|r| r.0), Some(400));
        assert_eq!(ranges.last().map(|r| r.1), Some(599));
        assert!(ranges.windows(2).all(|pair| pair[0].1 + 1 == pair[1].0));
        assert!(ranges.contains(&(502, 504, ErrorCode::ServerUnavailable)));
    }
}
