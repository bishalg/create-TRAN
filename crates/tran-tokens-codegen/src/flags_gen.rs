//! Feature flags typed accessors code generation (spec 029, REQ-CFG-001).
//!
//! Generates typed accessors for TypeScript, Swift, and Kotlin from `rust_core::flags::ALL_FLAGS`.
//! No client may read a flag by a string it spells itself.

use rust_core::flags::{FlagType, FlagValue, ALL_FLAGS};

use crate::names::pascal_case;

fn camel_case(snake: &str) -> String {
    let pascal = pascal_case(snake);
    let mut chars = pascal.chars();
    let first = chars.next().unwrap_or_default().to_ascii_lowercase();
    format!("{first}{}", chars.as_str())
}

fn screaming_case(snake: &str) -> String {
    snake.to_ascii_uppercase()
}

fn ts_value(val: &FlagValue) -> String {
    match val {
        FlagValue::Boolean(b) => b.to_string(),
        FlagValue::Integer(i) => i.to_string(),
        FlagValue::String(s) => format!("'{}'", s.replace('\'', "\\'")),
    }
}

fn swift_value(val: &FlagValue) -> String {
    match val {
        FlagValue::Boolean(b) => b.to_string(),
        FlagValue::Integer(i) => i.to_string(),
        FlagValue::String(s) => format!("\"{}\"", s.replace('"', "\\\"")),
    }
}

fn kotlin_value(val: &FlagValue) -> String {
    match val {
        FlagValue::Boolean(b) => b.to_string(),
        FlagValue::Integer(i) => format!("{i}L"),
        FlagValue::String(s) => format!("\"{}\"", s.replace('"', "\\\"")),
    }
}

fn ts_type(t: FlagType) -> &'static str {
    match t {
        FlagType::Boolean => "boolean",
        FlagType::Integer => "number",
        FlagType::String => "string",
    }
}

fn swift_type(t: FlagType) -> &'static str {
    match t {
        FlagType::Boolean => "Bool",
        FlagType::Integer => "Int64",
        FlagType::String => "String",
    }
}

fn kotlin_type(t: FlagType) -> &'static str {
    match t {
        FlagType::Boolean => "Boolean",
        FlagType::Integer => "Long",
        FlagType::String => "String",
    }
}

/// Renders TypeScript typed flag accessors (`packages/core-ts/src/generated/flags.ts`).
pub fn render_flags_ts() -> String {
    let mut out = String::from(
        "/**\n * @generated by tran-tokens-codegen from crates/rust-core/src/flags.rs — do not edit by hand.\n * Run `pnpm tokens:sync` after changing a flag in Rust.\n */\n\n",
    );

    out.push_str("export interface FlagsCatalogue {\n");
    for flag in ALL_FLAGS {
        let prop = camel_case(flag.id);
        out.push_str(&format!(
            "  readonly {prop}: {};\n",
            ts_type(flag.flag_type)
        ));
    }
    out.push_str("}\n\n");

    out.push_str("export const FLAGS = {\n");
    for flag in ALL_FLAGS {
        let camel = camel_case(flag.id);
        let id = flag.id;
        let def = ts_value(&flag.default_value);
        let live = flag.live;
        let typ = ts_type(flag.flag_type);
        out.push_str(&format!(
            "  {camel}: {{\n    id: '{id}',\n    defaultValue: {def},\n    live: {live},\n    get(flags?: Record<string, unknown> | null): {typ} {{\n      const val = flags?.[this.id];\n      return typeof val === '{typ}' ? (val as {typ}) : this.defaultValue;\n    }},\n  }},\n"
        ));
    }
    out.push_str("} as const;\n");

    out
}

/// Renders Swift typed flag accessors (`Generated/Flags.swift`).
pub fn render_flags_swift() -> String {
    let mut out = String::from(
        "// @generated by tran-tokens-codegen from crates/rust-core/src/flags.rs — do not edit by hand.\n// Run `pnpm tokens:sync` after changing a flag in Rust.\n\nimport Foundation\n\npublic enum Flags {\n",
    );

    for flag in ALL_FLAGS {
        let camel = camel_case(flag.id);
        let id = flag.id;
        let def = swift_value(&flag.default_value);
        let live = flag.live;
        let typ = swift_type(flag.flag_type);

        out.push_str(&format!(
            "    public static let {camel}Id = \"{id}\"\n    public static let {camel}Default: {typ} = {def}\n    public static let {camel}Live = {live}\n\n    public static func {camel}(from flags: [String: Any]?) -> {typ} {{\n        return flags?[{camel}Id] as? {typ} ?? {camel}Default\n    }}\n\n"
        ));
    }

    out.push_str("}\n");
    out
}

/// Renders Kotlin typed flag accessors (`generated/Flags.kt`).
pub fn render_flags_kotlin(package: &str) -> String {
    let mut out = format!(
        "package {package}\n\n/**\n * @generated by tran-tokens-codegen from crates/rust-core/src/flags.rs — do not edit by hand.\n * Run `pnpm tokens:sync` after changing a flag in Rust.\n */\nobject Flags {{\n"
    );

    for flag in ALL_FLAGS {
        let screaming = screaming_case(flag.id);
        let camel = camel_case(flag.id);
        let id = flag.id;
        let def = kotlin_value(&flag.default_value);
        let live = flag.live;
        let typ = kotlin_type(flag.flag_type);

        out.push_str(&format!(
            "    const val {screaming}_ID: String = \"{id}\"\n    const val {screaming}_DEFAULT: {typ} = {def}\n    const val {screaming}_LIVE: Boolean = {live}\n\n    fun {camel}(flags: Map<String, Any?>?): {typ} {{\n        val value = flags?.get({screaming}_ID)\n        return if (value is {typ}) value else {screaming}_DEFAULT\n    }}\n\n"
        ));
    }

    out.push_str("}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_flags_ts_contains_notify_me_accessor() {
        // Verifies: REQ-CFG-001
        let ts = render_flags_ts();
        assert!(ts.contains("notifyMe:"));
        assert!(ts.contains("id: 'notify_me'"));
        assert!(ts.contains("defaultValue: false"));
        assert!(ts.contains("live: true"));
    }

    #[test]
    fn render_flags_swift_contains_notify_me_accessor() {
        // Verifies: REQ-CFG-001
        let swift = render_flags_swift();
        assert!(swift.contains("public static let notifyMeId = \"notify_me\""));
        assert!(swift.contains("public static func notifyMe(from flags: [String: Any]?) -> Bool"));
    }

    #[test]
    fn render_flags_kotlin_contains_notify_me_accessor() {
        // Verifies: REQ-CFG-001
        let kotlin = render_flags_kotlin("com.tran.voting.generated");
        assert!(kotlin.contains("const val NOTIFY_ME_ID: String = \"notify_me\""));
        assert!(kotlin.contains("fun notifyMe(flags: Map<String, Any?>?): Boolean"));
    }

    #[test]
    fn helper_value_and_type_renderers() {
        assert_eq!(ts_value(&FlagValue::Integer(123)), "123");
        assert_eq!(
            ts_value(&FlagValue::String("str'ing".to_string())),
            "'str\\'ing'"
        );
        assert_eq!(swift_value(&FlagValue::Integer(123)), "123");
        assert_eq!(
            swift_value(&FlagValue::String("str\"ing".to_string())),
            "\"str\\\"ing\""
        );
        assert_eq!(kotlin_value(&FlagValue::Integer(123)), "123L");
        assert_eq!(
            kotlin_value(&FlagValue::String("str\"ing".to_string())),
            "\"str\\\"ing\""
        );

        assert_eq!(ts_type(FlagType::Integer), "number");
        assert_eq!(ts_type(FlagType::String), "string");
        assert_eq!(swift_type(FlagType::Integer), "Int64");
        assert_eq!(swift_type(FlagType::String), "String");
        assert_eq!(kotlin_type(FlagType::Integer), "Long");
        assert_eq!(kotlin_type(FlagType::String), "String");
    }
}
