//! Feature flags code generation (spec 029, REQ-CFG-001).
//!
//! Renders `rust_core::flags::ALL_FLAGS` to TypeScript (the whole catalogue plus typed accessors),
//! Swift and Kotlin (typed accessors). No client may read a flag by a string it spells itself, and
//! every platform reads a stored or fetched value alike: a value of the wrong type is the default.
//! In particular a JSON `1` is not `true` (Swift bridges `NSNumber(1)` to `Bool`, so the accessor
//! checks for a real boolean), and an integer is any whole number (org.json yields `Int` for small
//! numbers and `Long` for large ones).

use rust_core::flags::{
    FlagDefinition, FlagType, FlagValue, ALL_FLAGS, BUCKET_HEADER, CONFIG_POLICY,
};

use crate::names::pascal_case;

fn camel_case(snake: &str) -> String {
    let pascal = pascal_case(snake);
    let mut chars = pascal.chars();
    let first = chars.next().unwrap_or_default().to_ascii_lowercase();
    format!("{first}{}", chars.as_str())
}

fn screaming_case(snake: &str) -> String {
    snake.to_ascii_uppercase()
}

/// A single-quoted TypeScript string literal.
fn ts_str(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// A double-quoted Swift or Kotlin string literal.
fn c_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

fn ts_value(val: &FlagValue) -> String {
    match val {
        FlagValue::Boolean(b) => b.to_string(),
        FlagValue::Integer(i) => i.to_string(),
        FlagValue::String(s) => ts_str(s),
    }
}

fn swift_value(val: &FlagValue) -> String {
    match val {
        FlagValue::Boolean(b) => b.to_string(),
        FlagValue::Integer(i) => i.to_string(),
        FlagValue::String(s) => c_str(s),
    }
}

fn kotlin_value(val: &FlagValue) -> String {
    match val {
        FlagValue::Boolean(b) => b.to_string(),
        FlagValue::Integer(i) => format!("{i}L"),
        FlagValue::String(s) => c_str(s),
    }
}

fn ts_type(t: FlagType) -> &'static str {
    match t {
        FlagType::Boolean => "boolean",
        FlagType::Integer => "number",
        FlagType::String => "string",
    }
}

fn ts_flag_type(t: FlagType) -> &'static str {
    match t {
        FlagType::Boolean => "boolean",
        FlagType::Integer => "integer",
        FlagType::String => "string",
    }
}

fn swift_type(t: FlagType) -> &'static str {
    match t {
        FlagType::Boolean => "Bool",
        FlagType::Integer => "Int64",
        FlagType::String => "String",
    }
}

fn kotlin_type(t: FlagType) -> &'static str {
    match t {
        FlagType::Boolean => "Boolean",
        FlagType::Integer => "Long",
        FlagType::String => "String",
    }
}

/// The TypeScript test a raw value must pass to be read as this type.
fn ts_check(t: FlagType) -> &'static str {
    match t {
        FlagType::Boolean => "typeof value === 'boolean'",
        FlagType::Integer => "typeof value === 'number' && Number.isSafeInteger(value)",
        FlagType::String => "typeof value === 'string'",
    }
}

/// Renders TypeScript (`packages/core-ts/src/generated/flags.ts`) for the real catalogue.
pub fn render_flags_ts() -> String {
    render_flags_ts_for(ALL_FLAGS)
}

fn render_flags_ts_for(flags: &[FlagDefinition]) -> String {
    let mut out = String::from(
        "/**\n * @generated by tran-tokens-codegen from crates/rust-core/src/flags.rs — do not edit by hand.\n * Run `pnpm tokens:sync` after changing a flag in Rust.\n */\n\n",
    );
    out.push_str("/** The value types a flag may have (REQ-CFG-001). */\nexport type FlagType = 'boolean' | 'integer' | 'string';\n\n");
    out.push_str("/** A declared flag (REQ-CFG-001). */\nexport interface FlagDefinition {\n  readonly id: string;\n  readonly flagType: FlagType;\n  readonly defaultValue: boolean | number | string;\n  /** Applied as soon as a fetch brings it; otherwise read once at launch (REQ-CFG-005). */\n  readonly live: boolean;\n  readonly owner: string;\n  readonly purpose: string;\n  /** `YYYY-MM-DD`; `pnpm flags:check` fails after it (REQ-CFG-009). */\n  readonly expiry: string;\n}\n\n");
    out.push_str(&format!(
        "/** Remote configuration policy (REQ-CFG-004). */\nexport const CONFIG_POLICY = {{\n  maxAgeSeconds: {},\n}} as const;\n\n",
        CONFIG_POLICY.max_age_seconds
    ));
    out.push_str(&format!(
        "/** Carries the device's rollout bucket, 0 to 99 (REQ-CFG-006). */\nexport const BUCKET_HEADER = {};\n\n",
        ts_str(BUCKET_HEADER)
    ));

    out.push_str("/** Every declared flag (REQ-CFG-001). */\nexport const ALL_FLAGS: readonly FlagDefinition[] = [\n");
    for flag in flags {
        out.push_str(&format!(
            "  {{\n    id: {},\n    flagType: '{}',\n    defaultValue: {},\n    live: {},\n    owner: {},\n    purpose: {},\n    expiry: {},\n  }},\n",
            ts_str(flag.id),
            ts_flag_type(flag.flag_type),
            ts_value(&flag.default_value),
            flag.live,
            ts_str(flag.owner),
            ts_str(flag.purpose),
            ts_str(flag.expiry),
        ));
    }
    out.push_str("];\n\n");

    out.push_str("/** Every flag's value, typed. */\nexport interface FlagsCatalogue {\n");
    for flag in flags {
        out.push_str(&format!(
            "  readonly {}: {};\n",
            camel_case(flag.id),
            ts_type(flag.flag_type)
        ));
    }
    out.push_str("}\n\n");

    out.push_str("/** Raw flag values, as fetched or stored. */\nexport type FlagValues = Readonly<Record<string, unknown>> | null | undefined;\n\n");
    out.push_str("/** Typed accessors: a missing or wrong-typed value is the flag's default. */\nexport const FLAGS = {\n");
    for flag in flags {
        let typ = ts_type(flag.flag_type);
        out.push_str(&format!(
            "  {camel}: {{\n    id: {id},\n    defaultValue: {def} as {typ},\n    live: {live},\n    get(flags: FlagValues): {typ} {{\n      const value = flags?.[{id}];\n      return {check} ? value : {def};\n    }},\n  }},\n",
            camel = camel_case(flag.id),
            id = ts_str(flag.id),
            def = ts_value(&flag.default_value),
            live = flag.live,
            check = ts_check(flag.flag_type),
        ));
    }
    out.push_str("} as const;\n\n");

    out.push_str("/**\n * Every flag, typed: a `live` flag from the latest values, any other from the values at launch\n * (REQ-CFG-005).\n */\nexport function readFlags(launch: FlagValues, latest: FlagValues): FlagsCatalogue {\n  return {\n");
    for flag in flags {
        let camel = camel_case(flag.id);
        let source = if flag.live { "latest" } else { "launch" };
        out.push_str(&format!("    {camel}: FLAGS.{camel}.get({source}),\n"));
    }
    out.push_str("  };\n}\n");
    out
}

/// The Swift accessor body: a JSON `true` arrives as a `CFBoolean`, and `1` must not read as one.
fn swift_read(flag: &FlagDefinition, camel: &str) -> String {
    match flag.flag_type {
        FlagType::Boolean => format!(
            "        guard let number = flags?[{camel}Id] as? NSNumber,\n              CFGetTypeID(number) == CFBooleanGetTypeID()\n        else {{ return {camel}Default }}\n        return number.boolValue\n"
        ),
        FlagType::Integer => format!(
            "        guard let number = flags?[{camel}Id] as? NSNumber,\n              CFGetTypeID(number) != CFBooleanGetTypeID(),\n              let value = Int64(exactly: number.doubleValue)\n        else {{ return {camel}Default }}\n        return value\n"
        ),
        FlagType::String => format!("        return flags?[{camel}Id] as? String ?? {camel}Default\n"),
    }
}

/// Renders Swift typed flag accessors (`Generated/Flags.swift`).
pub fn render_flags_swift() -> String {
    render_flags_swift_for(ALL_FLAGS)
}

fn render_flags_swift_for(flags: &[FlagDefinition]) -> String {
    let mut out = String::from(
        "// @generated by tran-tokens-codegen from crates/rust-core/src/flags.rs — do not edit by hand.\n// Run `pnpm tokens:sync` after changing a flag in Rust.\n\nimport Foundation\n\n/// Typed flag accessors (REQ-CFG-001): a missing or wrong-typed value is the default.\npublic enum Flags {\n",
    );
    for flag in flags {
        let camel = camel_case(flag.id);
        let typ = swift_type(flag.flag_type);
        out.push_str(&format!(
            "    public static let {camel}Id = {id}\n    public static let {camel}Default: {typ} = {def}\n    public static let {camel}Live = {live}\n\n    public static func {camel}(from flags: [String: Any]?) -> {typ} {{\n{body}    }}\n\n",
            id = c_str(flag.id),
            def = swift_value(&flag.default_value),
            live = flag.live,
            body = swift_read(flag, &camel),
        ));
    }
    out.push_str("}\n");
    out
}

/// The Kotlin accessor body: org.json yields `Int` or `Long` (or a decimal) for a number.
fn kotlin_read(flag: &FlagDefinition, screaming: &str) -> String {
    match flag.flag_type {
        FlagType::Integer => format!(
            "        val number = flags?.get({screaming}_ID) as? Number ?: return {screaming}_DEFAULT\n        val whole = number.toLong()\n        return if (number.toDouble() == whole.toDouble()) whole else {screaming}_DEFAULT\n"
        ),
        _ => format!(
            "        val value = flags?.get({screaming}_ID)\n        return if (value is {typ}) value else {screaming}_DEFAULT\n",
            typ = kotlin_type(flag.flag_type)
        ),
    }
}

/// Renders Kotlin typed flag accessors (`generated/Flags.kt`).
pub fn render_flags_kotlin(package: &str) -> String {
    render_flags_kotlin_for(package, ALL_FLAGS)
}

fn render_flags_kotlin_for(package: &str, flags: &[FlagDefinition]) -> String {
    let mut out = format!(
        "package {package}\n\n/**\n * @generated by tran-tokens-codegen from crates/rust-core/src/flags.rs — do not edit by hand.\n * Run `pnpm tokens:sync` after changing a flag in Rust.\n *\n * Typed flag accessors (REQ-CFG-001): a missing or wrong-typed value is the default.\n */\nobject Flags {{\n"
    );
    for flag in flags {
        let screaming = screaming_case(flag.id);
        out.push_str(&format!(
            "    const val {screaming}_ID: String = {id}\n    const val {screaming}_DEFAULT: {typ} = {def}\n    const val {screaming}_LIVE: Boolean = {live}\n\n    fun {camel}(flags: Map<String, Any?>?): {typ} {{\n{body}    }}\n\n",
            id = c_str(flag.id),
            typ = kotlin_type(flag.flag_type),
            def = kotlin_value(&flag.default_value),
            live = flag.live,
            camel = camel_case(flag.id),
            body = kotlin_read(flag, &screaming),
        ));
    }
    out.push_str("}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Vec<FlagDefinition> {
        vec![
            FlagDefinition {
                id: "max_items",
                flag_type: FlagType::Integer,
                default_value: FlagValue::Integer(10),
                live: false,
                owner: "core",
                purpose: "A limit",
                expiry: "2030-01-01",
            },
            FlagDefinition {
                id: "banner_text",
                flag_type: FlagType::String,
                default_value: FlagValue::String("it's \"on\"".to_string()),
                live: true,
                owner: "growth",
                purpose: "Copy with a ' quote",
                expiry: "2030-01-01",
            },
        ]
    }

    #[test]
    fn ts_carries_the_whole_catalogue() {
        // Verifies: REQ-CFG-001
        let ts = render_flags_ts();
        assert!(ts.contains("export const CONFIG_POLICY = {\n  maxAgeSeconds: 300,\n} as const;"));
        assert!(ts.contains("export const BUCKET_HEADER = 'X-Tran-Bucket';"));
        assert!(ts.contains(
            "  {\n    id: 'notify_me',\n    flagType: 'boolean',\n    defaultValue: false,\n    live: true,\n    owner: 'growth',\n    purpose: 'Remind voter when registration opens',\n    expiry: '2027-01-01',\n  },"
        ));
        assert!(ts.contains("  readonly notifyMe: boolean;"));
        assert!(ts.contains("return typeof value === 'boolean' ? value : false;"));
        assert!(ts.contains("    notifyMe: FLAGS.notifyMe.get(latest),"));
    }

    #[test]
    fn ts_reads_integers_strictly_and_launch_flags_from_launch() {
        // Verifies: REQ-CFG-001 REQ-CFG-005
        let ts = render_flags_ts_for(&sample());
        assert!(
            ts.contains("typeof value === 'number' && Number.isSafeInteger(value) ? value : 10;")
        );
        assert!(ts.contains("    maxItems: FLAGS.maxItems.get(launch),"));
        assert!(ts.contains("    bannerText: FLAGS.bannerText.get(latest),"));
        assert!(ts.contains("flagType: 'integer'"));
        assert!(ts.contains("defaultValue: 'it\\'s \"on\"' as string"));
        assert!(ts.contains("purpose: 'Copy with a \\' quote'"));
    }

    #[test]
    fn swift_boolean_accessor_requires_a_real_boolean() {
        // Verifies: REQ-CFG-001
        let swift = render_flags_swift();
        assert!(swift.contains("public static let notifyMeId = \"notify_me\""));
        assert!(swift.contains("public static func notifyMe(from flags: [String: Any]?) -> Bool"));
        assert!(swift.contains("CFGetTypeID(number) == CFBooleanGetTypeID()"));
        assert!(!swift.contains("as? Bool"));
    }

    #[test]
    fn swift_integer_accessor_rejects_booleans_and_fractions() {
        // Verifies: REQ-CFG-001
        let swift = render_flags_swift_for(&sample());
        assert!(swift.contains("CFGetTypeID(number) != CFBooleanGetTypeID()"));
        assert!(swift.contains("let value = Int64(exactly: number.doubleValue)"));
        assert!(swift.contains("return flags?[bannerTextId] as? String ?? bannerTextDefault"));
        assert!(swift.contains("public static let bannerTextDefault: String = \"it's \\\"on\\\"\""));
    }

    #[test]
    fn kotlin_integer_accessor_accepts_any_whole_number() {
        // Verifies: REQ-CFG-001
        let kotlin = render_flags_kotlin_for("p", &sample());
        assert!(kotlin.contains(
            "val number = flags?.get(MAX_ITEMS_ID) as? Number ?: return MAX_ITEMS_DEFAULT"
        ));
        assert!(kotlin.contains(
            "return if (number.toDouble() == whole.toDouble()) whole else MAX_ITEMS_DEFAULT"
        ));
        assert!(!kotlin.contains("value is Long"));
        assert!(kotlin.contains("const val MAX_ITEMS_DEFAULT: Long = 10L"));
        assert!(kotlin.contains("return if (value is String) value else BANNER_TEXT_DEFAULT"));
    }

    #[test]
    fn kotlin_boolean_accessor() {
        // Verifies: REQ-CFG-001
        let kotlin = render_flags_kotlin("com.tran.voting.generated");
        assert!(kotlin.contains("const val NOTIFY_ME_ID: String = \"notify_me\""));
        assert!(kotlin.contains("fun notifyMe(flags: Map<String, Any?>?): Boolean"));
        assert!(kotlin.contains("return if (value is Boolean) value else NOTIFY_ME_DEFAULT"));
    }

    #[test]
    fn literal_escaping() {
        assert_eq!(ts_str("a\\b'c"), "'a\\\\b\\'c'");
        assert_eq!(c_str("a\\b\"c"), "\"a\\\\b\\\"c\"");
        assert_eq!(kotlin_value(&FlagValue::Boolean(true)), "true");
        assert_eq!(swift_value(&FlagValue::Integer(-3)), "-3");
    }
}
