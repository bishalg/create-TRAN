fn theme_block(selector: &str, theme: Option<&ThemeJson>) -> String {
    let theme = theme.expect("theme must exist in snapshot");
    let p = &theme.palette;
    format!(
        "{selector} {{\n  --tran-color-primary: {primary};\n  --tran-color-accent: {accent};\n  --tran-color-success: {success};\n  --tran-color-warning: {warning};\n  --tran-color-danger: {danger};\n  --tran-color-surface: {surface};\n  --tran-color-background: {background};\n  --tran-color-text-primary: {text_primary};\n  --tran-color-text-secondary: {text_secondary};\n  --tran-color-text-muted: {text_muted};\n  --tran-color-eligible: {eligible};\n  --tran-color-ineligible: {ineligible};\n  --tran-color-eligibility-neutral: {neutral};\n  --tran-glass-bg-standard: {glass_std};\n  --tran-glass-border-standard: {glass_border};\n  --tran-glass-shadow-ambient: {shadow_ambient};\n  --tran-glass-shadow-raised: {shadow_raised};\n}}\n",
        primary = p.primary,
        accent = p.accent,
        success = p.success,
        warning = p.warning,
        danger = p.danger,
        surface = p.surface,
        background = p.background,
        text_primary = p.text.primary,
        text_secondary = p.text.secondary,
        text_muted = p.text.muted,
        eligible = p.eligibility.canVote,
        ineligible = p.eligibility.cannotVote,
        neutral = p.eligibility.neutral,
        glass_std = theme.glass.background.standard,
        glass_border = theme.glass.border.standard,
        shadow_ambient = theme.glass.shadow.ambient,
        shadow_raised = theme.glass.shadow.raised,
    )
}

