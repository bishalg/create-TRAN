//! Writes platform design-token artifacts from `rust-core` brand tokens.

use rust_core::tokens::{ThemeJson, TokensJsonSnapshot};
use rust_core::tokens_json_snapshot;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    if let Err(err) = run() {
        eprintln!("tran-tokens-codegen: {err}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let root = workspace_root()?;
    let snapshot = tokens_json_snapshot();

    let core_generated = root.join("packages/core-ts/src/generated");
    let web_generated = root.join("apps/web/src/styles/generated");
    let native_generated = root.join("apps/native/src/generated");

    fs::create_dir_all(&core_generated).map_err(|e| e.to_string())?;
    fs::create_dir_all(&web_generated).map_err(|e| e.to_string())?;
    fs::create_dir_all(&native_generated).map_err(|e| e.to_string())?;

    let json_path = core_generated.join("tokens.json");
    let json = serde_json::to_string_pretty(&snapshot).map_err(|e| e.to_string())?;
    write_file(&json_path, format!("{json}\n"))?;

    let ts_path = core_generated.join("tokens.ts");
    write_file(&ts_path, render_tokens_ts(&snapshot))?;

    let css_path = web_generated.join("theme.css");
    write_file(&css_path, render_theme_css(&snapshot))?;

    let native_path = native_generated.join("brandTokens.ts");
    write_file(&native_path, render_native_stub())?;

    println!("tran-tokens-codegen: wrote {}", json_path.display());
    println!("tran-tokens-codegen: wrote {}", ts_path.display());
    println!("tran-tokens-codegen: wrote {}", css_path.display());
    println!("tran-tokens-codegen: wrote {}", native_path.display());
    Ok(())
}

fn workspace_root() -> Result<PathBuf, String> {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let root = manifest
        .parent()
        .and_then(|p| p.parent())
        .ok_or_else(|| "could not resolve workspace root".to_string())?;
    Ok(root.to_path_buf())
}

fn write_file(path: &Path, contents: String) -> Result<(), String> {
    fs::write(path, contents).map_err(|e| format!("write {}: {e}", path.display()))
}

fn render_tokens_ts(snapshot: &TokensJsonSnapshot) -> String {
    let out = String::from(
        "/**\n * @generated by tran-tokens-codegen — do not edit by hand.\n * Run `pnpm tokens:sync` after changing rust-core tokens.\n */\n\nimport snapshot from './tokens.json' with { type: 'json' };\n\nexport type ThemeMode = 'light' | 'dark';\n\nexport interface ThemeTokens {\n  mode: ThemeMode;\n  glass: {\n    background: {\n      subtle: string;\n      standard: string;\n      prominent: string;\n      dark: string;\n    };\n    border: {\n      subtle: string;\n      standard: string;\n      highlight: string;\n    };\n    blur: {\n      sm: string;\n      md: string;\n      lg: string;\n      xl: string;\n    };\n    shadow: {\n      ambient: string;\n      raised: string;\n      insetGlow: string;\n    };\n  };\n  radii: typeof snapshot.radii;\n  palette: {\n    primary: string;\n    primaryGlow: string;\n    accent: string;\n    success: string;\n    warning: string;\n    danger: string;\n    surface: string;\n    background: string;\n    eligibility: {\n      canVote: string;\n      cannotVote: string;\n      neutral: string;\n    };\n    text: {\n      primary: string;\n      secondary: string;\n      muted: string;\n    };\n  };\n}\n\nexport type LiquidGlassTokens = ThemeTokens;\n\nexport const themeTokens: Record<ThemeMode, ThemeTokens> = {\n  light: snapshot.themes.light as ThemeTokens,\n  dark: snapshot.themes.dark as ThemeTokens,\n};\n\nexport function getThemeTokens(mode: ThemeMode = 'dark'): ThemeTokens {\n  return themeTokens[mode];\n}\n\n/** Default export for backward compatibility — dark theme. */\nexport const liquidGlassTokens = themeTokens.dark;\n\nexport const designTypography = snapshot.typography;\nexport const designSpacing = snapshot.spacing;\n",
    );

    let _ = snapshot.themes.get("light");
    let _ = snapshot.themes.get("dark");
    out
}

fn render_theme_css(snapshot: &TokensJsonSnapshot) -> String {
    let mut css =
        String::from("/* @generated by tran-tokens-codegen — do not edit by hand. */\n\n");
    css.push_str(&theme_block(
        ":root, [data-theme=\"dark\"]",
        snapshot.themes.get("dark"),
    ));
    css.push('\n');
    css.push_str(&theme_block(
        "[data-theme=\"light\"]",
        snapshot.themes.get("light"),
    ));
    css.push_str("\n\n[data-theme=\"light\"] {\n  color-scheme: light;\n}\n\n:root,\n[data-theme=\"dark\"] {\n  color-scheme: dark;\n}\n");
    css
}

fn theme_block(selector: &str, theme: Option<&ThemeJson>) -> String {
    let theme = theme.expect("theme must exist in snapshot");
    let p = &theme.palette;
    format!(
        "{selector} {{\n  --tran-font-family: {font};\n  --tran-spacing-sm: {space_sm};\n  --tran-spacing-md: {space_md};\n  --tran-radius-md: {radius_md};\n  --tran-color-primary: {primary};\n  --tran-color-accent: {accent};\n  --tran-color-success: {success};\n  --tran-color-warning: {warning};\n  --tran-color-danger: {danger};\n  --tran-color-surface: {surface};\n  --tran-color-background: {background};\n  --tran-color-text-primary: {text_primary};\n  --tran-color-text-secondary: {text_secondary};\n  --tran-color-eligible: {eligible};\n  --tran-color-ineligible: {ineligible};\n  --tran-color-eligibility-neutral: {neutral};\n  --tran-glass-bg-standard: {glass_std};\n  --tran-glass-border-standard: {glass_border};\n}}\n",
        font = snapshot_typography_font(),
        space_sm = "0.5rem",
        space_md = "1rem",
        radius_md = theme.radii.md,
        primary = p.primary,
        accent = p.accent,
        success = p.success,
        warning = p.warning,
        danger = p.danger,
        surface = p.surface,
        background = p.background,
        text_primary = p.text.primary,
        text_secondary = p.text.secondary,
        eligible = p.eligibility.canVote,
        ineligible = p.eligibility.cannotVote,
        neutral = p.eligibility.neutral,
        glass_std = theme.glass.background.standard,
        glass_border = theme.glass.border.standard,
    )
}

fn snapshot_typography_font() -> &'static str {
    "-apple-system, BlinkMacSystemFont, 'SF Pro Display', 'Segoe UI', Roboto, sans-serif"
}

fn render_native_stub() -> String {
    r"/**
 * @generated by tran-tokens-codegen — do not edit by hand.
 * React Native consumes the same semantic tokens as web via @tran/core for now.
 * Future: SwiftUI / Compose outputs will live under tooling/design-tokens/.
 */

export {
  getThemeTokens,
  liquidGlassTokens,
  themeTokens,
  type LiquidGlassTokens,
  type ThemeMode,
  type ThemeTokens,
} from '@tran/core';
"
    .to_string()
}
