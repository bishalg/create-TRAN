//! `packages/core-ts/src/generated/rules.ts` — rule data from `rust-core` (ADR-0027, REQ-RULE-010).
//!
//! Only data crosses: constants, the supported-country table, validation messages, the session
//! and device policies, the push actions, and the permission and personal-question catalogues
//! (`privacy_ts.rs`). The small TypeScript functions that use them are pinned to Rust by
//! `fixtures/vote-eligibility.json`, `fixtures/session.json`, `fixtures/permissions.json` and
//! `fixtures/push.json`.

use crate::privacy_ts::render_privacy_ts;
use rust_core::push::{PushAction, DEVICE_POLICY};
use rust_core::rate::RATE_POLICY;
use rust_core::session::SESSION_POLICY;
use rust_core::stored_records::{
    CURRENT_CONFIG_SCHEMA, CURRENT_PUSH_SCHEMA, CURRENT_SESSION_SCHEMA,
};
use rust_core::{VoteValidationError, DEFAULT_VOTING_AGE, MAX_AGE, SUPPORTED_COUNTRIES};

fn ts_string(value: &str) -> String {
    format!("'{}'", value.replace('\\', "\\\\").replace('\'', "\\'"))
}

pub fn render_rules_ts() -> String {
    let countries: String = SUPPORTED_COUNTRIES
        .iter()
        .map(|c| {
            format!(
                "  {{ countryCode: {}, minimumAge: {} }},\n",
                ts_string(c.country_code),
                c.minimum_age
            )
        })
        .collect();
    let messages: String = VoteValidationError::ALL
        .iter()
        .map(|e| format!("  {}: {},\n", e.key(), ts_string(&e.to_string())))
        .collect();
    let session = format!(
        "  accessTtlSeconds: {},\n  refreshTtlSeconds: {},\n  tokenBytes: {},\n",
        SESSION_POLICY.access_ttl_seconds,
        SESSION_POLICY.refresh_ttl_seconds,
        SESSION_POLICY.token_bytes
    );
    let device = format!(
        "  staleAfterDays: {},\n  refreshAfterDays: {},\n",
        DEVICE_POLICY.stale_after_days, DEVICE_POLICY.refresh_after_days
    );
    let push_actions: Vec<String> = PushAction::ALL
        .iter()
        .map(|action| ts_string(action.as_str()))
        .collect();

    let rate = format!(
        "  auth: {{\n    sustainedPerMinute: {},\n    burst: {},\n  }},\n  write: {{\n    sustainedPerMinute: {},\n    burst: {},\n  }},\n  read: {{\n    sustainedPerMinute: {},\n    burst: {},\n  }},\n  maxKeys: {},\n  maxInFlight: {},\n",
        RATE_POLICY.auth.sustained_per_minute,
        RATE_POLICY.auth.burst,
        RATE_POLICY.write.sustained_per_minute,
        RATE_POLICY.write.burst,
        RATE_POLICY.read.sustained_per_minute,
        RATE_POLICY.read.burst,
        RATE_POLICY.max_keys,
        RATE_POLICY.max_in_flight,
    );

    format!(
        "/**\n * @generated by tran-tokens-codegen from crates/rust-core — do not edit by hand.\n * Run `pnpm tokens:sync` after changing a rule in Rust.\n */\n\n\
import type {{ TranStringKey }} from './keys.js';\n\
import type {{ ElementId }} from './screens.js';\n\n\
export const DEFAULT_VOTING_AGE = {DEFAULT_VOTING_AGE};\n\n\
export const MAX_AGE = {MAX_AGE};\n\n\
export interface CountryVotingAge {{\n  readonly countryCode: string;\n  readonly minimumAge: number;\n}}\n\n\
/** Supported countries, sorted by code (REQ-RULE-009). */\n\
export const SUPPORTED_COUNTRIES: readonly CountryVotingAge[] = [\n{countries}];\n\n\
/** Exact validation messages (REQ-RULE-006). */\n\
export const VALIDATION_MESSAGES = {{\n{messages}}} as const;\n\n\
/** Token lifetimes in seconds and token size in bytes (REQ-SEC-005). */\n\
export const SESSION_POLICY = {{\n{session}}} as const;\n\n\
/** Days before the API prunes an unrefreshed registration, and the apps' refresh (REQ-PSH-005). */\n\
export const DEVICE_POLICY = {{\n{device}}} as const;\n\n\
/** What an app does after `push_sync` (REQ-PSH-009). */\n\
export type PushAction = {push_action};\n\n\
/** A route's rate-limiting class (REQ-RL-001). */\n\
export type RouteClass = 'auth' | 'write' | 'read' | 'exempt';\n\n\
export interface ClassPolicy {{\n  readonly sustainedPerMinute: number;\n  readonly burst: number;\n}}\n\n\
export interface RatePolicy {{\n  readonly auth: ClassPolicy;\n  readonly write: ClassPolicy;\n  readonly read: ClassPolicy;\n  readonly maxKeys: number;\n  readonly maxInFlight: number;\n}}\n\n\
/** Rate limiting policy defaults (REQ-RL-001). */\n\
export const RATE_POLICY: RatePolicy = {{\n{rate}}} as const;\n\n\
/** Current client stored record schema versions (REQ-DB-011). */\n\
export const STORED_RECORD_SCHEMAS = {{\n  session: {CURRENT_SESSION_SCHEMA},\n  push: {CURRENT_PUSH_SCHEMA},\n  config: {CURRENT_CONFIG_SCHEMA},\n}} as const;\n\n\
/** What a client does with a stored record version (REQ-DB-011). */\n\
export type StoredRecordAction = 'use' | 'upgrade' | 'discard';\n\n{privacy}",
        push_action = push_actions.join(" | "),
        privacy = render_privacy_ts(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rules_ts_carries_the_rate_policy() {
        // Verifies: REQ-RL-001
        let ts = render_rules_ts();
        assert!(ts.contains("export const RATE_POLICY: RatePolicy = {"));
        assert!(ts.contains("sustainedPerMinute: 10,"));
        assert!(ts.contains("maxInFlight: 100,"));
        assert!(ts.contains("export type RouteClass = 'auth' | 'write' | 'read' | 'exempt';"));
    }

    #[test]
    fn rules_ts_carries_every_country_and_message() {
        let ts = render_rules_ts();
        assert!(ts.contains("@generated by tran-tokens-codegen"));
        assert!(ts.contains("export const MAX_AGE = 150;"));
        assert!(ts.contains("{ countryCode: 'BR', minimumAge: 16 },"));
        assert_eq!(
            ts.matches("countryCode: '").count(),
            SUPPORTED_COUNTRIES.len()
        );
        assert!(ts.contains("  ageOutOfRange: 'Age must be 150 or less',"));
    }

    #[test]
    fn rules_ts_carries_the_session_policy() {
        // Verifies: REQ-SEC-005
        let ts = render_rules_ts();
        assert!(ts.contains(
            "export const SESSION_POLICY = {\n  accessTtlSeconds: 900,\n  refreshTtlSeconds: 2592000,\n  tokenBytes: 32,\n} as const;"
        ));
    }

    #[test]
    fn rules_ts_carries_the_device_policy_and_push_actions() {
        // Verifies: REQ-PSH-005 REQ-PSH-009
        let ts = render_rules_ts();
        assert!(ts.contains(
            "export const DEVICE_POLICY = {\n  staleAfterDays: 60,\n  refreshAfterDays: 7,\n} as const;"
        ));
        assert!(ts.contains("export type PushAction = 'register' | 'unregister' | 'nothing';"));
    }

    #[test]
    fn rules_ts_carries_stored_record_schemas() {
        // Verifies: REQ-DB-011
        let ts = render_rules_ts();
        assert!(ts.contains("export const STORED_RECORD_SCHEMAS = {"));
        assert!(ts.contains("session: 2,"));
        assert!(ts.contains("export type StoredRecordAction = 'use' | 'upgrade' | 'discard';"));
    }

    #[test]
    fn ts_strings_escape_quotes_and_backslashes() {
        assert_eq!(ts_string(r"it's \ ok"), r"'it\'s \\ ok'");
    }
}
