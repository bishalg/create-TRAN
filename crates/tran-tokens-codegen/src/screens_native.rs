//! iOS `Generated/ScreenContract.swift` and Android `generated/ScreenContract.kt`: the screen
//! contract's element ids, one constant per element and screen, plus the platform's minimums
//! (ADR-0038, REQ-SCR-002, REQ-SCR-007). Feature code and UI tests use these, never a literal.
//! An element another platform offers alone (the web's skip link) gets no constant here.

use crate::names::pascal_case;
use crate::screens_ts::member_from_id;
use rust_core::screens::{PlatformMinimum, Screen, TextScale};

/// `200` → `2.0`, `150` → `1.5`.
fn factor(percent: u16) -> String {
    format!("{:?}", f64::from(percent) / 100.0)
}

pub fn render_screen_contract_swift(screens: &[Screen], minimum: &PlatformMinimum) -> String {
    let mut out = String::from(
        "// @generated by tran-tokens-codegen from crates/rust-core/src/screens.rs — do not edit by hand.\n// Run `pnpm tokens:sync` after changing the screen contract (ADR-0038).\n\nimport CoreGraphics\n\n/// Element ids of the screen contract: the only names `accessibilityIdentifier` and the UI tests\n/// use (REQ-SCR-002).\nenum ScreenContract {\n",
    );
    for screen in screens {
        out.push_str(&format!("    enum {} {{\n", pascal_case(screen.id)));
        for element in screen.elements.iter().filter(|e| e.is_on(minimum.platform)) {
            out.push_str(&format!(
                "        static let {} = \"{}\"\n",
                member_from_id(element.id),
                element.id
            ));
        }
        out.push_str("    }\n\n");
    }
    let scale = match minimum.largest_text_scale {
        TextScale::Category(name) => {
            format!("static let largestContentSizeCategory = \"{name}\"")
        }
        TextScale::Percent(percent) => {
            format!("static let largestTextScale: CGFloat = {}", factor(percent))
        }
    };
    out.push_str(&format!(
        "    /// Minimums from `PLATFORM_MINIMUMS` (REQ-SCR-007), in {unit}.\n    enum Minimums {{\n        static let control: CGFloat = {control}\n        static let primaryAction: CGFloat = {primary}\n        {scale}\n    }}\n}}\n",
        unit = minimum.unit,
        control = minimum.control,
        primary = minimum.primary_action,
    ));
    out
}

pub fn render_screen_contract_kotlin(
    screens: &[Screen],
    minimum: &PlatformMinimum,
    kotlin_package: &str,
) -> String {
    let mut out = format!(
        "// @generated by tran-tokens-codegen from crates/rust-core/src/screens.rs — do not edit by hand.\n// Run `pnpm tokens:sync` after changing the screen contract (ADR-0038).\n\npackage {kotlin_package}\n\n/** Element ids of the screen contract: the only names `testTag` and the UI tests use (REQ-SCR-002). */\nobject ScreenContract {{\n",
    );
    for screen in screens {
        out.push_str(&format!("    object {} {{\n", pascal_case(screen.id)));
        for element in screen.elements.iter().filter(|e| e.is_on(minimum.platform)) {
            out.push_str(&format!(
                "        const val {} = \"{}\"\n",
                member_from_id(element.id),
                element.id
            ));
        }
        out.push_str("    }\n\n");
    }
    let scale = match minimum.largest_text_scale {
        TextScale::Percent(percent) => {
            format!("const val largestFontScale: Float = {}f", factor(percent))
        }
        TextScale::Category(name) => format!("const val largestTextCategory = \"{name}\""),
    };
    out.push_str(&format!(
        "    /** Minimums from `PLATFORM_MINIMUMS` (REQ-SCR-007), in {unit}. */\n    object Minimums {{\n        const val control: Int = {control}\n        const val primaryAction: Int = {primary}\n        {scale}\n    }}\n}}\n",
        unit = minimum.unit,
        control = minimum.control,
        primary = minimum.primary_action,
    ));
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use rust_core::screens::{platform_minimum, Platform, SCREENS};

    #[test]
    fn factors_keep_a_decimal_point() {
        assert_eq!(factor(200), "2.0");
        assert_eq!(factor(150), "1.5");
    }

    // Verifies: REQ-SCR-002 REQ-SCR-007
    #[test]
    fn swift_carries_ids_per_screen_and_the_ios_minimums() {
        let ios = platform_minimum(Platform::Ios);
        let swift = render_screen_contract_swift(&SCREENS, &ios);
        assert!(swift.contains("    enum AuthWelcome {\n        static let voterBranchButton = \"voter-branch-button\"\n"));
        assert!(swift.contains("        static let control: CGFloat = 44\n"));
        assert!(swift.contains(
            "static let largestContentSizeCategory = \"UICTContentSizeCategoryAccessibilityXXXL\""
        ));
        let percent = PlatformMinimum {
            largest_text_scale: TextScale::Percent(200),
            ..ios
        };
        assert!(render_screen_contract_swift(&SCREENS, &percent)
            .contains("static let largestTextScale: CGFloat = 2.0"));
    }

    // Verifies: REQ-SCR-002 REQ-SCR-007
    #[test]
    fn kotlin_carries_ids_per_screen_and_the_android_minimums() {
        let android = platform_minimum(Platform::Android);
        let kotlin = render_screen_contract_kotlin(&SCREENS, &android, "com.example");
        assert!(kotlin.contains("package com.example\n"));
        assert!(kotlin.contains("        const val checkButton = \"check-button\"\n"));
        assert!(kotlin.contains("        const val control: Int = 48\n"));
        assert!(kotlin.contains("const val largestFontScale: Float = 2.0f"));
        let category = PlatformMinimum {
            largest_text_scale: TextScale::Category("huge"),
            ..android
        };
        assert!(render_screen_contract_kotlin(&SCREENS, &category, "p")
            .contains("const val largestTextCategory = \"huge\""));
    }
}
