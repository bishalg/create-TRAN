//! `packages/core-ts/src/generated/screens.ts` — the screen contract from `rust-core` (ADR-0038,
//! REQ-SCR-001). Labels and intents are typed as `TranStringKey`, so a contract entry whose locale
//! string is missing fails `tsc`; the data is Rust's own serialization, so every platform reads the
//! same JSON.

use crate::names::pascal_case;
use rust_core::screens::{
    unique_elements, ElementKind, Given, Screen, ScreensJsonSnapshot, Then, When,
};

/// `age-field` → `ageField`, `auth_welcome` → `authWelcome`: the member name on every platform.
pub fn member_from_id(id: &str) -> String {
    let pascal = pascal_case(id);
    let mut chars = pascal.chars();
    chars
        .next()
        .map(|first| first.to_ascii_lowercase().to_string() + chars.as_str())
        .unwrap_or_default()
}

fn union(items: impl IntoIterator<Item = String>) -> String {
    items
        .into_iter()
        .map(|item| format!("\n  | {item}"))
        .collect()
}

fn quoted(items: &[&str]) -> String {
    union(items.iter().map(|item| format!("'{item}'")))
}

/// `ScreenIds.<screen>.<element>`: the constants `data-testid` uses (REQ-SCR-002).
pub fn render_id_table(screens: &[Screen]) -> String {
    let mut out = String::from("export const ScreenIds = {\n");
    for screen in screens {
        out.push_str(&format!("  {}: {{\n", member_from_id(screen.id)));
        for element in screen.elements {
            out.push_str(&format!(
                "    {}: '{}',\n",
                member_from_id(element.id),
                element.id
            ));
        }
        out.push_str("  },\n");
    }
    out.push_str("} as const;\n");
    out
}

pub fn render_screens_ts(snapshot: &ScreensJsonSnapshot) -> String {
    let screen_ids: Vec<&str> = snapshot.screens.iter().map(|s| s.id).collect();
    let destinations: Vec<&str> = snapshot
        .screens
        .iter()
        .map(|s| s.destination.as_str())
        .collect();
    let element_ids: Vec<&str> = unique_elements().iter().map(|e| e.id).collect();
    let kinds: Vec<&str> = ElementKind::ALL.iter().map(|k| k.as_str()).collect();
    format!(
        "/**\n * @generated by tran-tokens-codegen from crates/rust-core/src/screens.rs — do not edit by hand.\n * Run `pnpm tokens:sync` after changing the screen contract in Rust (ADR-0038).\n */\n\n\
import type {{ TranStringKey }} from './keys.js';\n\n\
export type ScreenId ={screen_ids};\n\n\
export type ScreenDestination ={destinations};\n\n\
export type ElementId ={element_ids};\n\n\
/** What an element is, never how it looks (REQ-SCR-003). */\n\
export type ElementKind ={kinds};\n\n\
export type TouchClass = 'control' | 'primary' | 'none';\n\n\
export type Presence = 'always' | {{ readonly when: string }};\n\n\
export type SessionKind = 'none' | 'unauthenticated' | 'citizen_voter' | 'election_auditor';\n\n\
export interface MessageArg {{\n  readonly name: string;\n  readonly value: string;\n}}\n\n\
export interface ExpectedMessage {{\n  readonly id: ElementId;\n  readonly key: TranStringKey;\n  readonly args: readonly MessageArg[];\n}}\n\n\
/** The closed verb set (ADR-0038): {given}. */\n\
export type Given =\n  | {{ readonly session: SessionKind }}\n  | 'api_reachable'\n  | 'api_unreachable'\n  | {{ readonly locale: string }}\n  | {{ readonly theme: string }}\n  | 'largest_text_scale'\n  | 'reduced_motion';\n\n\
/** {when}. `type` replaces the field's content. */\n\
export type When =\n  | {{ readonly tap: ElementId }}\n  | {{ readonly type: {{ readonly id: ElementId; readonly text: string }} }}\n  | {{ readonly select: {{ readonly id: ElementId; readonly option: string }} }}\n  | {{ readonly press_key: {{ readonly id: ElementId; readonly key: string }} }}\n  | 'go_offline'\n  | 'go_online';\n\n\
/** {then}. */\n\
export type Then =\n  | {{ readonly exists: ElementId }}\n  | {{ readonly missing: ElementId }}\n  | {{ readonly text_is: ExpectedMessage }}\n  | {{ readonly has_focus: ElementId }}\n  | {{ readonly announced: ExpectedMessage }}\n  | {{ readonly count: {{ readonly id: ElementId; readonly n: number }} }};\n\n\
export interface Scenario {{\n  readonly name: string;\n  readonly verifies: readonly string[];\n  readonly given: readonly Given[];\n  readonly when: readonly When[];\n  readonly then: readonly Then[];\n  readonly within_ms: number;\n}}\n\n\
export interface ScreenElement {{\n  readonly id: ElementId;\n  readonly kind: ElementKind;\n  readonly label: TranStringKey;\n  readonly touch: TouchClass;\n  readonly presence: Presence;\n  /** Where the element is offered (REQ-SCR-008). */\n  readonly platforms: readonly ('web' | 'ios' | 'android')[];\n}}\n\n\
export interface Screen {{\n  readonly id: ScreenId;\n  readonly destination: ScreenDestination;\n  readonly intent: TranStringKey;\n  readonly elements: readonly ScreenElement[];\n  readonly scenarios: readonly Scenario[];\n}}\n\n\
export type TextScale = {{ readonly percent: number }} | {{ readonly category: string }};\n\n\
/** Touch minimums and the largest text scale per platform (REQ-SCR-007). */\n\
export interface PlatformMinimum {{\n  readonly platform: 'web' | 'ios' | 'android';\n  readonly unit: string;\n  readonly control: number;\n  readonly primary_action: number;\n  readonly largest_text_scale: TextScale;\n}}\n\n\
export const SCREENS: readonly Screen[] = {screens};\n\n\
export const PLATFORM_MINIMUMS: readonly PlatformMinimum[] = {minimums};\n\n\
/** No scenario may take longer: the indicator delay plus the server deadline (REQ-SCR-004). */\n\
export const SCENARIO_BOUND_MS = {bound};\n\n\
/** Element ids by screen: `data-testid={{ScreenIds.eligibility.checkButton}}` (REQ-SCR-002). */\n\
{ids}",
        screen_ids = quoted(&screen_ids),
        destinations = quoted(&destinations),
        element_ids = quoted(&element_ids),
        kinds = quoted(&kinds),
        given = Given::VERBS.join(", "),
        when = When::VERBS.join(", "),
        then = Then::VERBS.join(", "),
        screens = pretty(&snapshot.screens),
        minimums = pretty(&snapshot.platform_minimums),
        bound = snapshot.scenario_bound_ms,
        ids = render_id_table(snapshot.screens),
    )
}

/// Rust's own serialization, so the data matches the schema test in `rust-core` (REQ-SCR-003).
fn pretty<T: serde::Serialize>(value: &T) -> String {
    serde_json::to_string_pretty(value).expect("the contract is plain data")
}

#[cfg(test)]
mod tests {
    use super::*;
    use rust_core::screens_json_snapshot;

    #[test]
    fn member_names_fold_ids() {
        assert_eq!(member_from_id("age-field"), "ageField");
        assert_eq!(member_from_id("auth_welcome"), "authWelcome");
        assert_eq!(member_from_id(""), "");
    }

    // Verifies: REQ-SCR-001
    #[test]
    fn screens_ts_carries_the_contract_and_the_ids() {
        let ts = render_screens_ts(&screens_json_snapshot());
        assert!(ts.contains("@generated by tran-tokens-codegen"));
        assert!(ts.contains("export type ScreenId =\n  | 'splash'\n  | 'auth_welcome'"));
        assert!(ts.contains("  eligibility: {\n    signOutButton: 'sign-out-button',"));
        assert!(ts.contains("\"label\": \"eligibility.age.label\""));
        assert!(ts.contains("export const SCENARIO_BOUND_MS = 4300;"));
        assert!(ts.contains("\"control\": 24,\n    \"primary_action\": 44,"));
    }
}
